// ---------------------------------------------------------------- main
async function main() {
  const now = new Date();
  const today = ymd(now);

  const { LANGS, pathFor } = await load('src/data/languages.js');
  const { STR } = await load('src/data/translations.js');
  const { MENU, MENU_VERSION } = await load('src/data/menu.js');
  const { ROOM_RATES, RATE_SLOTS } = await load('src/data/room-rates.js');
  const { buildFaq } = await load('src/data/faq.js');
  let icsUrl = 'https://app.realitydn.com/api/feed/v1/events.ics';
  try { icsUrl = (await load('src/data/feed.js')).FEED_ICS_URL || icsUrl; } catch { /* keep default */ }

  const en = STR.EN;
  let geo = null;
  try {
    const html = readFileSync(join(ROOT, 'index.html'), 'utf8');
    const lat = html.match(/"latitude":\s*([\d.-]+)/);
    const lng = html.match(/"longitude":\s*([\d.-]+)/);
    if (lat && lng) geo = { lat: lat[1], lng: lng[1] };
  } catch { /* coordinates are optional */ }

  const p = en.infoHost.pricing;
  const rates = ROOM_RATES.map(({ id, rates: r }) =>
    `${p.spaces[id]}: ` + RATE_SLOTS.map((s) =>
      `${p.slotsLabel[s]} ${p.slots[s]} ${r[s] == null ? p.unavailable.toLowerCase() : `${r[s]}k VND/hr`}`
    ).join(', ')
  );

  const events = readSnapshot();
  if (!events) console.warn('  ! build-seo-files: no usable feed-snapshot.json — skipping events sections');
  const { lineup, upcoming } = eventSections(events, now);

  const files = {
    'sitemap.xml': buildSitemap({ LANGS, pathFor }, today),
    'llms.txt': buildLlms({ en, today, geo, lineup, ranges: menuRanges(MENU), rates, icsUrl, menuVersion: MENU_VERSION }),
    'llms-full.txt': buildLlmsFull({
      en, today, geo, rates, upcoming, icsUrl,
      faqEN: buildFaq(makeT(STR, 'EN'), 'EN'),
      faqVI: buildFaq(makeT(STR, 'VN'), 'VN'),
      menu: menuFull(MENU),
    }),
  };
  for (const [name, body] of Object.entries(files)) {
    writeFileSync(join(PUB, name), body, 'utf8');
    console.log(`  ✓ build-seo-files: public/${name} (${body.length} chars)`);
  }
}

main().catch((err) => {
  // Never fail the deploy — the previously committed files stay in place.
  console.warn('  ! build-seo-files failed (non-fatal, keeping existing files):', err && err.message);
  process.exit(0);
});
