/**
 * build-seo-files.mjs — writes public/sitemap.xml, public/llms.txt and
 * public/llms-full.txt from the site's own sources of truth, so none of them
 * can drift from what the pages say:
 *
 *   LANGS (src/data/languages.js)   → sitemap URLs + hreflang alternates
 *   locales/en.js + vi.js           → facts, rules, FAQ, event guidelines
 *   src/data/faq.js                 → the same FAQ the FAQPage JSON-LD emits
 *   src/data/menu.js                → price ranges + the full priced menu
 *   src/data/room-rates.js          → room rental rates
 *   src/data/feed.js                → the ICS feed URL
 *   index.html                      → geo coordinates (LocalBusiness JSON-LD)
 *   public/feed-snapshot.json       → weekly lineup + next 14 days of events
 *
 * Runs in `prebuild` AFTER fetch-feed.mjs (so the snapshot is fresh); Vite
 * then copies public/ into dist/. Deterministic for a given day + snapshot:
 * no random ordering, dates in Đà Nẵng time (UTC+7).
 *
 * FAIL-SOFT, like fetch-feed.mjs: a missing/broken snapshot only drops the
 * events sections, and any other error leaves the previously committed files
 * in place and exits 0 — this script must never fail a deploy.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execSync } from 'node:child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const PUB = join(ROOT, 'public');
const SITE = 'https://realitydn.com';
const ICT = 'Asia/Ho_Chi_Minh';
const UPCOMING_DAYS = 14;

const load = (rel) => import(pathToFileURL(join(ROOT, rel)).href);

// 'YYYY-MM-DD' in Đà Nẵng time.
const ymd = (d) => new Intl.DateTimeFormat('en-CA', { timeZone: ICT, year: 'numeric', month: '2-digit', day: '2-digit' }).format(d);
const hm = (d) => new Intl.DateTimeFormat('en-GB', { timeZone: ICT, hour: '2-digit', minute: '2-digit', hour12: false }).format(d);
const weekday = (d) => new Intl.DateTimeFormat('en-US', { timeZone: ICT, weekday: 'long' }).format(d);
const dayLabel = (d) => new Intl.DateTimeFormat('en-GB', { timeZone: ICT, weekday: 'short', day: 'numeric', month: 'short' }).format(d);
const WEEK_ORDER = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
const oneLine = (s) => String(s || '').replace(/\s+/g, ' ').trim();

function makeT(STR, lang) {
  const lookup = (root, k) => k.split('.').reduce((a, c) => (a && a[c] !== undefined ? a[c] : undefined), root);
  return {
    use: (k) => {
      const v = lookup(STR[lang], k);
      if (v !== undefined) return v;
      const en = lookup(STR.EN, k);
      return en !== undefined ? en : k;
    },
  };
}

// Last commit date touching the given paths (for pages that don't change per
// build); falls back to today when git isn't available (e.g. a bare tarball).
function gitDate(paths, fallback) {
  try {
    const out = execSync(`git log -1 --format=%cs -- ${paths.join(' ')}`, { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] })
      .toString().trim();
    return /^\d{4}-\d{2}-\d{2}$/.test(out) ? out : fallback;
  } catch {
    return fallback;
  }
}

function readSnapshot() {
  try {
    const snap = JSON.parse(readFileSync(join(PUB, 'feed-snapshot.json'), 'utf8'));
    return Array.isArray(snap.events) ? snap.events : null;
  } catch {
    return null;
  }
}

const costText = (ev) => (ev.cost ? `entry ${ev.cost}` : 'free');

// ---------------------------------------------------------------- sitemap
function buildSitemap({ LANGS, pathFor }, today) {
  const guidelinesDate = gitDate(['src/pages/EventGuidelines.jsx', 'src/data/locales'], today);
  // /host-guide/ is a noindex stub — deliberately absent.
  const pages = [
    { base: '/', lastmod: today, changefreq: 'daily', priority: '1.0' },
    { base: '/event-guidelines', lastmod: guidelinesDate, changefreq: 'monthly', priority: '0.6' },
  ];
  const alts = (base) => [
    ...LANGS.map((l) => `    <xhtml:link rel="alternate" hreflang="${l.iso}" href="${SITE}${pathFor(l.code, base)}"/>`),
    `    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE}${pathFor('EN', base)}"/>`,
  ].join('\n');
  const urls = pages.flatMap((p) => LANGS.map((l) => [
    '  <url>',
    `    <loc>${SITE}${pathFor(l.code, p.base)}</loc>`,
    `    <lastmod>${p.lastmod}</lastmod>`,
    `    <changefreq>${p.changefreq}</changefreq>`,
    `    <priority>${p.priority}</priority>`,
    alts(p.base),
    '  </url>',
  ].join('\n')));
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- GENERATED by scripts/build-seo-files.mjs at prebuild — do not edit.',
    '     Every language twin lists all six alternates (+ x-default), trailing-',
    '     slash URLs (the form the host serves without a redirect). The noindex',
    '     /host-guide/ stub is intentionally omitted. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
    '        xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ...urls,
    '</urlset>',
    '',
  ].join('\n');
}

// ---------------------------------------------------------------- events
function eventSections(events, now) {
  if (!events) return { lineup: null, upcoming: null };
  const nowMs = now.getTime();
  const horizon = nowMs + UPCOMING_DAYS * 86400000;
  const live = events.filter((e) => e && e.startsAt && e.status !== 'cancelled' && !Number.isNaN(Date.parse(e.startsAt)));
  const soon = live
    .filter((e) => Date.parse(e.startsAt) >= nowMs && Date.parse(e.startsAt) < horizon)
    .sort((a, b) => Date.parse(a.startsAt) - Date.parse(b.startsAt) || String(a.title_en).localeCompare(String(b.title_en)));

  // Weekly lineup: series with 3+ instances in the snapshot window that still
  // have one in the next two weeks — i.e. the recurring nights, not one-offs.
  const counts = new Map();
  for (const e of live) if (e.seriesId) counts.set(e.seriesId, (counts.get(e.seriesId) || 0) + 1);
  const seen = new Set();
  const recurring = [];
  for (const e of soon) {
    if (!e.seriesId || seen.has(e.seriesId) || (counts.get(e.seriesId) || 0) < 3) continue;
    seen.add(e.seriesId);
    recurring.push(e);
  }
  const byDay = new Map(WEEK_ORDER.map((d) => [d, []]));
  for (const e of recurring) byDay.get(weekday(new Date(e.startsAt))).push(e);
  const lineup = WEEK_ORDER
    .filter((d) => byDay.get(d).length)
    .map((d) => {
      const items = byDay.get(d)
        .sort((a, b) => hm(new Date(a.startsAt)).localeCompare(hm(new Date(b.startsAt))))
        .map((e) => `${hm(new Date(e.startsAt))} ${oneLine(e.title_en)} (${costText(e)})`);
      return `- ${d}: ${items.join('; ')}`;
    });

  const upcoming = soon.map((e) => {
    const d = new Date(e.startsAt);
    const end = e.endsAt ? `–${hm(new Date(e.endsAt))}` : '';
    const where = e.location?.name_en ? ` · ${oneLine(e.location.name_en)}` : '';
    const host = e.host ? ` · hosted by ${oneLine(e.host)}` : '';
    const link = e.sourceUrl ? ` — ${e.sourceUrl}` : '';
    return `- ${dayLabel(d)} ${hm(d)}${end} · ${oneLine(e.title_en)}${where}${host} · ${costText(e)}${link}`;
  });
  return { lineup, upcoming };
}

// ---------------------------------------------------------------- menu
function menuRanges(MENU) {
  return MENU.map((cat) => {
    // Add-ons ("Add raw wild honey + lime", 5k) are not drinks — keep them out of the range.
    const prices = cat.sections.flatMap((s) => s.items
      .filter((i) => !/^add\s/i.test(i.nameEN || ''))
      .map((i) => Number(i.price)).filter((n) => Number.isFinite(n) && n > 0));
    if (!prices.length) return null;
    const lo = Math.min(...prices), hi = Math.max(...prices);
    return `- ${cat.labelEN}: ${lo === hi ? `${lo}k` : `${lo}k–${hi}k`} VND`;
  }).filter(Boolean);
}

function menuFull(MENU) {
  const out = [];
  for (const cat of MENU) {
    out.push(`### ${cat.labelEN} / ${cat.labelVI || cat.labelEN}`, '');
    for (const s of cat.sections) {
      out.push(`#### ${s.labelEN}${s.labelVI && s.labelVI !== s.labelEN ? ` / ${s.labelVI}` : ''}`, '');
      for (const i of s.items) {
        const vi = i.nameVI && i.nameVI !== i.nameEN ? ` / ${i.nameVI}` : '';
        const price = Number(i.price) > 0 ? ` — ${Number(i.price) * 1000} VND (${i.price}k)` : '';
        const desc = i.descEN ? ` — ${oneLine(i.descEN)}` : '';
        out.push(`- ${i.nameEN}${vi}${price}${desc}`);
      }
      out.push('');
    }
  }
  return out;
}

